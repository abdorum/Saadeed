def sura_name(sura: int) -> str:
    return SURA_NAMES[sura - 1]


def citation(sura: int, aya_from: int, aya_to: int | None = None) -> str:
    """صيغة الإحالة المعتمدة: «البقرة: 255» أو «الأحزاب: 70–71»."""
    if aya_to and aya_to != aya_from:
        return f"{sura_name(sura)}: {aya_from}–{aya_to}"
    return f"{sura_name(sura)}: {aya_from}"
