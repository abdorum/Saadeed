# متغيرات اختيارية: إن غابت لا يظهر مكانها شيء (لا «—»).
_OPTIONAL = {"found_elsewhere", "draft_note", "alternative_note"}


def render(template: str, facts: dict[str, Any]) -> str:
    """يملأ القالب. المتغير الناقص يصير «—» ولا يرمي استثناءً."""
    safe: defaultdict[str, str] = defaultdict(lambda: "—")
    safe.update({k: "" for k in _OPTIONAL})
    safe.update({k: str(v) for k, v in facts.items() if v is not None})
    return template.format_map(safe)


def explanation_for(rule_id: str, facts: dict[str, Any]) -> str:
    return render(EXPLANATIONS.get(rule_id, EXPLANATIONS["BR-00"]), facts)


def next_step_for(rule_id: str, facts: dict[str, Any]) -> str:
    return render(NEXT_STEPS.get(rule_id, NEXT_STEPS["BR-00"]), facts)
