"""قرائن المتن (FR-34 الخفيفة، ADR-0014): علامات يذكرها نقاد الحديث في متون ما لا يصح.

مأخوذة من الضوابط التي ذكرها ابن القيم في «المنار المنيف»، ومنها «المجازفات» التي لا يقول مثلها
النبي ﷺ: الثواب العظيم على العمل اليسير، وتخصيص يوم بعينه بفضل محدد، وتشبيه أجر العمل بأجر الأنبياء.

**يوم الجمعة مستثنى عمدًا**: لفضائله أحاديث ثابتة كثيرة خارج الكتب الستة.

**القرينة لا تحكم.** ترفع أثر الخطأ لحديث لم يُعثر عليه (BR-23)، ولا تغيّر حالة الدليل،
ولا تُستعمل مع حديث وُجد في المخزن. والأنماط حتمية على النص المطبَّع.
"""

from __future__ import annotations

import re

from saadeed.text.normalize import normalize

_NUM = r"(?:\d+|عشر|عشره|عشرين|ثلاثين|اربعين|خمسين|سبعين|ثمانين|مايه|ماييه|مئه|ماه|الف|الفي|الفين|الاف|مليون)"
_DAY = r"(?:السبت|الاحد|الاثنين|الثلاثا|الاربعا|الخميس)"

SIGNS: list[tuple[str, re.Pattern[str]]] = [
    (
        "مبالغة في الثواب على عمل يسير",
        re.compile(
            rf"(?:غفر الله له|غفر له|كتب الله له|كتب له|اعطاه الله|اعطي|بني الله له|بني له|كان له|له اجر|له ثواب)"
            rf"(?:\s+\S+){{0,6}}\s+{_NUM}\s+(?:\S+\s+){{0,2}}"
            rf"(?:سنه|عام|حجه|عمره|شهيد|نبي|قصر|قصور|مدينه|حسنه|درجه|حوراء|ملك)"
        ),
    ),
    (
        "تخصيص يوم من الأسبوع بفضل محدد لعمل بعينه",
        re.compile(
            rf"(?:من|فمن)\s+(?:قرا|صلي|صام|اغتسل|تصدق|ذكر)(?:\s+\S+){{0,8}}\s+(?:يوم|ليله)\s+{_DAY}"
        ),
    ),
    (
        "تشبيه أجر العمل بأجر الأنبياء",
        re.compile(rf"(?:ثواب|اجر)\s+(?:{_NUM}\s+)?(?:نبي|نبيا|الانبياء|الانبيا)"),
    ),
]


def matn_signs(text: str) -> list[str]:
    """أسماء القرائن الموجودة في النص (قد تكون فارغة)."""
    norm = " " + normalize(text) + " "
    return [name for name, pat in SIGNS if pat.search(norm)]
